#!/usr/bin/env python3
"""Writes src/game/countryShapes.js: simplified outlines (Natural Earth 50m, public domain) of the countries in the
building data, for the silhouette on the veiled globe. Usage: make-country-shapes.py [path/to/ne_50m_admin_0_countries.geojson]
(downloads it when no path is given). Re-run it after adding a building in a new country."""
import json, re, sys, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
URL = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson'
TOL = 0.25  # degrees; Douglas-Peucker


def dp(pts, tol):
    if len(pts) < 3:
        return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    norm = (dx * dx + dy * dy) ** 0.5 or 1e-9
    far, idx = 0, 0
    for i in range(1, len(pts) - 1):
        d = abs(dy * pts[i][0] - dx * pts[i][1] + x2 * y1 - y2 * x1) / norm
        if d > far:
            far, idx = d, i
    if far <= tol:
        return [pts[0], pts[-1]]
    return dp(pts[: idx + 1], tol)[:-1] + dp(pts[idx:], tol)


def simplify_ring(ring, tol):
    # A closed ring has no baseline, so simplify its two halves.
    mid = len(ring) // 2
    return dp(ring[: mid + 1], tol)[:-1] + dp(ring[mid:], tol)[:-1]


def area(ring):
    return abs(sum(a[0] * b[1] - b[0] * a[1] for a, b in zip(ring, ring[1:] + ring[:1]))) / 2


codes = sorted({b['location']['countryCode'] for b in json.loads((ROOT / 'src/main/resources/data/buildings.json').read_text())})
src = Path(sys.argv[1]).read_text() if len(sys.argv) > 1 else urllib.request.urlopen(URL).read().decode()
features = json.loads(src)['features']

def code_of(p):
    for key in ('ISO_A2_EH', 'ISO_A2', 'WB_A2'):
        if p.get(key) and p[key] != '-99':
            return p[key]

out = {}
for f in features:
    code = code_of(f['properties'])
    if code not in codes:
        continue
    g = f['geometry']
    polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
    rings = [p[0] for p in polys]  # outer rings only
    biggest = max(area(r) for r in rings)
    kept = []
    for r in rings:
        if area(r) < biggest * 0.01 and len(rings) > 1:
            continue  # specks next to the mainland
        s = simplify_ring([(round(x, 1), round(y, 1)) for x, y in r], TOL if biggest > 4 else 0.03)
        if len(s) >= 3:
            kept.append(s)
    out[code] = kept

missing = [c for c in codes if c not in out]
lines = ['// Generated by scripts/make-country-shapes.py (Natural Earth, public domain). Outer rings of [lon, lat] per country code.',
         'export const SHAPES = {']
for c in sorted(out):
    lines.append(f'  {c}: {json.dumps([[list(map(list, [(round(x, 1), round(y, 1)) for x, y in r])) for r in out[c]]][0], separators=(",", ":"))},')
lines.append('}\n')
(ROOT / 'frontend/src/game/countryShapes.js').write_text('\n'.join(lines))
print('written', len(out), 'countries; missing:', missing)
